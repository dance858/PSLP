#!/bin/sh
# Keeps the symbols that libPSLP exports free of name clashes.
#
# Every function with external linkage that is not part of the public API
# (cmake/public_symbols.txt) gets the prefix pslp_ through the generated header
# include/core/pslp_namespace.h, which CMake force-includes into every source
# file of the library and of the tests.
#
#   pslp_symbols.sh generate <lib>...   rewrite the header from the libraries
#   pslp_symbols.sh check <lib>...      fail if a symbol is exported unprefixed
#
# After adding or removing a function that is not static, build the library
# and run 'generate' on it. To cover the functions that only exist in some
# configurations, pass both a Release build and a Debug build with
# -DPSLP_BUILD_TESTING=ON.

set -eu

prefix=pslp_
here=$(cd "$(dirname "$0")" && pwd)
public="$here/public_symbols.txt"
header="$here/../include/core/pslp_namespace.h"

usage()
{
    sed -n '2,15p' "$0" | sed 's/^# \{0,1\}//'
    exit 2
}

# Prints the defined global symbols of the given libraries, one per line.
# Names that start with an underscore belong to the toolchain and are skipped.
exported()
{
    if [ "$(uname)" = Darwin ]; then
        strip_underscore='s/^_//'   # Mach-O puts an underscore before C names
    else
        strip_underscore=''
    fi
    for lib in "$@"; do
        nm -g "$lib"
    done | awk 'NF == 3 && $2 ~ /^[A-TV-Z]$/ { print $3 }' |
        sed "$strip_underscore" | { grep -v '^_' || true; } | LC_ALL=C sort -u
}

[ $# -ge 2 ] || usage
mode=$1
shift
for lib in "$@"; do
    if [ ! -f "$lib" ]; then
        echo "pslp_symbols.sh: no such library: $lib" >&2
        exit 1
    fi
done

case $mode in
generate)
    names=$(exported "$@" | sed "s/^$prefix//" |
        { grep -vxF -f "$public" || true; } | LC_ALL=C sort -u)
    {
        cat <<'EOF'
/*
 * Copyright 2025-2026 Daniel Cederberg
 *
 * This file is part of the PSLP project (LP Presolver).
 *
 * Licensed under the Apache License, Version 2.0 (the "License");
 * you may not use this file except in compliance with the License.
 * You may obtain a copy of the License at
 *
 *     http://www.apache.org/licenses/LICENSE-2.0
 *
 * Unless required by applicable law or agreed to in writing, software
 * distributed under the License is distributed on an "AS IS" BASIS,
 * WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.
 * See the License for the specific language governing permissions and
 * limitations under the License.
 */

/* Generated by cmake/pslp_symbols.sh, do not edit by hand.

   Gives every internal function with external linkage the prefix pslp_, so
   that the symbols of libPSLP cannot clash with those of a program or library
   that embeds it. CMake force-includes this header into every source file of
   the library and of the tests; the sources keep using the short names. The
   public functions (PSLP_API.h) are not renamed. */

#ifndef PSLP_NAMESPACE_H
#define PSLP_NAMESPACE_H

/* clang-format off */
EOF
        for name in $names; do
            echo "#define $name $prefix$name"
        done
        printf '/* clang-format on */\n\n#endif /* PSLP_NAMESPACE_H */\n'
    } >"$header"
    echo "wrote $(echo "$names" | wc -l | tr -d ' ') names to $header"
    ;;
check)
    symbols=$(exported "$@")
    bad=$(echo "$symbols" | grep -v "^$prefix" | grep -vxF -f "$public" || true)
    missing=$(echo "$symbols" | LC_ALL=C sort -u |
        LC_ALL=C comm -13 - "$public" || true)
    status=0
    if [ -n "$bad" ]; then
        echo "Exported without the $prefix prefix and not in public_symbols.txt:"
        echo "$bad" | sed 's/^/  /'
        echo "Make the function static, or rebuild and run"
        echo "  sh cmake/pslp_symbols.sh generate <lib>..."
        status=1
    fi
    if [ -n "$missing" ]; then
        echo "Listed in public_symbols.txt but not exported:"
        echo "$missing" | sed 's/^/  /'
        status=1
    fi
    [ $status -eq 0 ] && echo "exported symbols OK ($(echo "$symbols" | wc -l | tr -d ' '))"
    exit $status
    ;;
*)
    usage
    ;;
esac
